"""Create or update the demo departments, roles, dataset catalog and grants. Idempotent."""

from __future__ import annotations

from typing import Any

from django.core.management.base import BaseCommand
from django.db import transaction

from accounts.models import Department, Role
from catalog import seed_data as sd
from catalog.models import Dataset, DatasetColumn, RoleDatasetGrant


class Command(BaseCommand):
    help = "Seed demo departments, roles, datasets (catalog entries only) and grants."

    @transaction.atomic
    def handle(self, *args: Any, **options: Any) -> None:
        depts = {
            slug: Department.objects.update_or_create(slug=slug, defaults={"name": name})[0]
            for slug, name in sd.DEPARTMENTS.items()
        }
        roles: dict[str, Role] = {}
        for dept_slug, items in sd.ROLES.items():
            for slug, name, ceiling, selectable, desc in items:
                roles[slug] = Role.objects.update_or_create(
                    department=depts[dept_slug],
                    slug=slug,
                    defaults={
                        "name": name,
                        "max_sensitivity": ceiling,
                        "is_self_selectable": selectable,
                        "description": desc,
                    },
                )[0]

        datasets: dict[str, Dataset] = {}
        for slug, spec in sd.DATASETS.items():
            ds, _ = Dataset.objects.update_or_create(
                slug=slug,
                defaults={
                    "name": spec["name"],
                    "owner_department": depts[spec["dept"]],
                    "sensitivity": spec["sens"],
                    "storage_type": Dataset.Storage.POSTGRES,
                    "location": spec["table"],
                    "license_note": "Synthetic demo data generated by seed_demo_tables",
                },
            )
            for name, dtype, sens, pii in spec["columns"]:
                DatasetColumn.objects.update_or_create(
                    dataset=ds,
                    name=name,
                    defaults={"data_type": dtype, "sensitivity": sens, "is_pii": pii},
                )
            datasets[slug] = ds

        for role_slug, grants in sd.GRANTS.items():
            for spec in grants:
                ds = datasets[spec["dataset"]]
                all_cols = list(ds.columns.all())
                role = roles[role_slug]
                if spec["columns"] == sd.ALL:
                    cols = [c for c in all_cols if c.sensitivity <= role.max_sensitivity]
                elif spec["columns"] == sd.NON_PII:
                    cols = [
                        c
                        for c in all_cols
                        if not c.is_pii and c.sensitivity <= role.max_sensitivity
                    ]
                else:
                    cols = [c for c in all_cols if c.name in spec["columns"]]
                grant, _ = RoleDatasetGrant.objects.update_or_create(
                    role=role,
                    dataset=ds,
                    defaults={
                        "aggregate_only": spec["agg"],
                        "min_group_size": spec["min_group"],
                        "row_filter": spec["row_filter"],
                    },
                )
                grant.columns.set(cols)
        self.stdout.write(
            self.style.SUCCESS(
                f"Seeded {len(depts)} departments, {len(roles)} roles, {len(datasets)} datasets."
            )
        )
